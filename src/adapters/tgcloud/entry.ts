/**
 * Synthetic modules that exist only inside a `/run` request.
 *
 * `/run` executes a module from the module space sent with the request and
 * only modules under a runnable directory (`handlers/`, `endpoints/`) can be
 * the entry point. A job lives in `lib/`, which is deployed but not runnable
 * and not reachable from a Mini App. Adding a small `endpoints/` module to the
 * request, and never to a deploy, keeps jobs off the public surface.
 */

export const ENTRY_MODULE = 'endpoints/tgcron_entry';
export const BACKUP_MODULE = 'endpoints/tgcron_backup';

const MODULE_NAME = /^lib(\/[A-Za-z0-9_-]+)+$/;

export interface TickInfo {
  readonly job: string;
  readonly runId: string;
  /** ISO time the schedule was due, or null for a manual run. */
  readonly scheduledAt: string | null;
}

/** Source of the entry module that calls `jobModule`'s default export. */
export function entrySource(jobModule: string): string {
  if (!MODULE_NAME.test(jobModule)) {
    throw new Error(`job module must be a module name under lib/, got "${jobModule}"`);
  }
  return [
    '// Generated by tgcloud-cron for a single /run call. Never deployed.',
    `import job from '../${jobModule}.js';`,
    '',
    'export default function (input) {',
    '  return job(input.args, input.tick);',
    '}',
    '',
  ].join('\n');
}

/**
 * The module space for a run: the project's modules plus synthetic ones.
 * Refuses to shadow a real module with the same name.
 */
export function moduleSpace(
  modules: Readonly<Record<string, string>>,
  extra: Readonly<Record<string, string>>,
): Record<string, string> {
  for (const name of Object.keys(extra)) {
    if (name in modules) {
      throw new Error(
        `the project has its own module "${name}"; rename it, tgcloud-cron reserves this name`,
      );
    }
  }
  return { ...modules, ...extra };
}

/**
 * Exporter run inside the isolate. The isolate has no Buffer, atob or btoa,
 * so blobs are base64-encoded by hand. Values that JSON cannot carry are
 * tagged: `{ "$base64": "..." }` for bytes, `{ "$bigint": "..." }` for
 * integers beyond 2^53.
 *
 * Operations:
 *   { op: "tables" }                                  -> [{ name, withoutRowid }]
 *   { op: "page", table, after, limit }              -> { rows, last }    (rowid tables)
 *   { op: "page", table, offset, limit, noRowid }    -> { rows }          (WITHOUT ROWID)
 */
export const BACKUP_SOURCE = `// Generated by tgcloud-cron for backup /run calls. Never deployed.
import { db } from 'sdk';

const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

function base64(bytes) {
  let out = '';
  let i = 0;
  for (; i + 2 < bytes.length; i += 3) {
    const n = (bytes[i] << 16) | (bytes[i + 1] << 8) | bytes[i + 2];
    out += B64[n >> 18] + B64[(n >> 12) & 63] + B64[(n >> 6) & 63] + B64[n & 63];
  }
  if (i < bytes.length) {
    const n = (bytes[i] << 16) | ((bytes[i + 1] ?? 0) << 8);
    out += B64[n >> 18] + B64[(n >> 12) & 63];
    out += i + 1 < bytes.length ? B64[(n >> 6) & 63] + '=' : '==';
  }
  return out;
}

function encode(value) {
  if (value instanceof Uint8Array) return { $base64: base64(value) };
  if (value instanceof ArrayBuffer) return { $base64: base64(new Uint8Array(value)) };
  if (typeof value === 'bigint') return { $bigint: String(value) };
  return value;
}

function quote(name) {
  return '"' + String(name).replace(/"/g, '""') + '"';
}

export default async function (input) {
  if (input.op === 'tables') {
    const rows = await db.all(
      "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    );
    return rows.map((r) => ({ name: r.name, withoutRowid: /WITHOUT\\s+ROWID/i.test(r.sql || '') }));
  }
  if (input.op === 'page') {
    const table = quote(input.table);
    if (input.noRowid) {
      const rows = await db.all('SELECT * FROM ' + table + ' LIMIT :limit OFFSET :offset', {
        ':limit': input.limit,
        ':offset': input.offset,
      });
      return { rows: rows.map((r) => Object.fromEntries(Object.entries(r).map(([k, v]) => [k, encode(v)]))) };
    }
    const rows = await db.all(
      'SELECT rowid AS __tgcron_rowid, * FROM ' + table + ' WHERE rowid > :after ORDER BY rowid LIMIT :limit',
      { ':after': input.after, ':limit': input.limit },
    );
    let last = input.after;
    const out = rows.map((r) => {
      last = Number(r.__tgcron_rowid);
      const row = {};
      for (const [k, v] of Object.entries(r)) if (k !== '__tgcron_rowid') row[k] = encode(v);
      return row;
    });
    return { rows: out, last };
  }
  throw new Error('unknown op ' + input.op);
}
`;
